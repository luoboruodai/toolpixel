inline Glyph procedural(std::uint16_t cp, int style) {
    Glyph glyph{};
    const int index = cp & 0xFF;
    if (style == 9) {
        for (int y = 0; y < 8; ++y) for (int x = 0; x < 8; ++x) {
            if ((index + x * 3 + y * 5) % 11 < index % 9) glyph[y] |= 1 << x;
        }
    } else if (style == 10) {
        for (int y = 0; y < 4; ++y) for (int x = 0; x < 2; ++x) {
            if (index & (1 << (y * 2 + x))) {
                glyph[y * 2] |= 3 << (x * 4);
                glyph[y * 2 + 1] |= 3 << (x * 4);
            }
        }
    } else if (style == 11) {
        for (int y = 0; y < 2; ++y) for (int x = 0; x < 2; ++x) {
            if (index & (1 << (y * 2 + x))) {
                for (int row = 0; row < 4; ++row) glyph[y * 4 + row] |= 0xF << (x * 4);
            }
        }
    } else if (style == 12) {
        const int height = index % 9;
        for (int y = 0; y < height; ++y) glyph[y] = 0xFF;
    } else if (style == 13) {
        const int center = index % 8;
        for (int x = 0; x < 8; ++x) {
            const int distance = std::abs(x - center);
            if (distance < 4) glyph[7 - distance * 2] |= 1 << x;
        }
    } else if (style == 14) {
        for (int y = 0; y < 8; ++y) {
            glyph[y] = ((index * 37 + y * 19) ^ (index << (y % 3))) & 0xFF;
            if ((index + y) % 4 == 0) glyph[y] |= 0x80;
        }
    } else if (cp == 0x2591 || cp == 0x2592 || cp == 0x2593) {
        const int density = cp == 0x2591 ? 1 : (cp == 0x2592 ? 2 : 3);
        for (int y = 0; y < 8; ++y) for (int x = 0; x < 8; ++x) {
            if ((x + y * 2) % 4 < density) glyph[y] |= 1 << x;
        }
    } else if (cp == 0x2588) {
        glyph.fill(0xFF);
    }
    return glyph;
}

inline Glyph glyph_for(std::uint16_t cp, int style) {
    if (cp >= 32 && cp < 127) return kBasic[cp - 32];
    if (cp >= 0x30A0 && cp < 0x30A0 + static_cast<int>(kKana.size())) return kKana[cp - 0x30A0];
    if (cp >= 0x2800 && cp <= 0x28FF) {
        Glyph glyph{};
        const int index = cp - 0x2800;
        for (int y = 0; y < 4; ++y) for (int x = 0; x < 2; ++x) {
            if (index & (1 << (y * 2 + x))) {
                glyph[y * 2] |= 3 << (x * 4);
                glyph[y * 2 + 1] |= 3 << (x * 4);
            }
        }
        return glyph;
    }
    return procedural(cp, style);
}

inline float coverage(const Glyph& glyph, float x, float y) {
    const int px = static_cast<int>(std::floor(std::clamp(x, 0.0f, 0.9999f) * 8.0f));
    const int py = static_cast<int>(std::floor(std::clamp(y, 0.0f, 0.9999f) * 8.0f));
    return (glyph[py] & (1 << px)) ? 1.0f : 0.0f;
}

inline std::vector<std::uint16_t> preset(int style) {
    const auto ascii = [](const char* text) {
        std::vector<std::uint16_t> result;
        while (*text) result.push_back(static_cast<unsigned char>(*text++));
        return result;
    };
    switch (style) {
        case 2: return ascii(" .,:;ilwW#@");
        case 3: return ascii(" .:coPO#%@");
        case 4: return ascii(" 01");
        case 5: return ascii(" 0123456789ABCDEF");
        case 6: return ascii(" .:ilwWMO#@");
        case 7: return {32, 0x2591, 0x2592, 0x2593, 0x2588};
        case 8: return {32, 0x30A0, 0x30A1, 0x30A2, 0x30A3, 0x30A4, 0x30A5, 0x30A6, 0x30A7, 0x30A8, 0x30A9};
        default: {
            std::vector<std::uint16_t> result{32};
            const int count = style == 9 ? 12 : (style == 10 ? 32 : (style == 14 ? 32 : 16));
            const std::uint16_t base = style == 9 ? 0xE000 : (style == 10 ? 0x2800 : (0xE000 + style * 0x100));
            for (int index = 1; index < count; ++index) result.push_back(base + index);
            return result;
        }
    }
}

inline std::vector<std::uint16_t> active_ramp(int style, const std::vector<std::uint16_t>& custom) {
    auto result = style == 1 && !custom.empty() ? custom : preset(style);
    if (result.empty()) result = {32};
    if (result.size() > 64) result.resize(64);
    return result;
}

inline std::string description(int style, const std::vector<std::uint16_t>& custom) {
    const auto ramp = active_ramp(style, custom);
    std::string result;
    for (const std::uint16_t cp : ramp) {
        if (cp < 0x80) result.push_back(static_cast<char>(cp));
        else result += "U+" + std::to_string(cp) + " ";
    }
    return result;
}

inline std::uint32_t hash(int x, int y, int frame) {
    std::uint32_t value = static_cast<std::uint32_t>(x) * 0x45D9F3Bu ^ static_cast<std::uint32_t>(y) * 0x119DE1F3u ^ static_cast<std::uint32_t>(frame) * 0x27D4EB2Du;
    value ^= value >> 16;
    value *= 0x7FEB352Du;
    value ^= value >> 15;
    return value;
}

inline float noise(int x, int y, int frame = 0) {
    return static_cast<float>(hash(x, y, frame) & 0xFFFFFF) / 16777215.0f;
}

